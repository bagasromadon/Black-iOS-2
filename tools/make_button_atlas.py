#!/usr/bin/env python3
"""Packs the touch button artwork into one atlas and writes the two headers the host code includes.

    python3 tools/make_button_atlas.py "path/to/With Button"

Reads the 15 button PNGs (fire.png, aim.png, ... see FILES) from that folder and writes
  native/button_atlas.h      the cell table (UVs, circle centre), read by touch.cpp
  native/button_atlas_png.h  the atlas PNG as a byte array, decoded once by vulkan.cpp
Every source image is a full-width circle; a button with a letter/arrow badge is taller, with the circle at the
bottom. All are scaled to the same width and bottom-aligned, so one circle centre fits every cell.
Needs Pillow.
"""
import io
import sys
from pathlib import Path

from PIL import Image

S = 320          # width every button is scaled to
PAD = 4          # transparent border around each cell, against bleeding when sampled
COLS = 5
SRC_W, SRC_TALL = 2693, 2925  # the artwork's own size: the circle's width, the height with a badge on top
TH = round(S * SRC_TALL / SRC_W)  # cell height

# enum name, file in the folder
FILES = [
    ("Aim", "aim.png"),
    ("Back", "back.png"),
    ("Crouch", "crouch.png"),
    ("Fire", "fire.png"),
    ("Mode", "firing mode.png"),
    ("Grenade", "grenade.png"),
    ("Gyro", "gyroscope.png"),
    ("Health", "health_pack.png"),
    ("Use", "interact.png"),
    ("Melee", "melee.png"),
    ("Pause", "pause.png"),
    ("Reload", "reload.png"),
    ("Suppressor", "suppressor.png"),
    ("WeaponPrev", "weapon down.png"),
    ("WeaponNext", "weapon up.png"),
]


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    src = Path(sys.argv[1])
    rows = -(-len(FILES) // COLS)
    cw, ch = S + 2 * PAD, TH + 2 * PAD
    aw, ah = cw * COLS, ch * rows
    atlas = Image.new("RGBA", (aw, ah), (0, 0, 0, 0))
    cells = []
    for i, (name, f) in enumerate(FILES):
        im = Image.open(src / f).convert("RGBA")
        tall = im.height > im.width * 1.05
        im = im.resize((S, TH if tall else S), Image.LANCZOS)  # Pillow resizes RGBA premultiplied
        x, y = (i % COLS) * cw + PAD, (i // COLS) * ch + PAD
        atlas.alpha_composite(im, (x, y + TH - im.height))  # circles sit at the bottom of the cell
        cells.append((name, x / aw, y / ah, (x + S) / aw, (y + TH) / ah))
    # flat colours with soft edges: a 256-colour palette with alpha keeps it sharp at a fraction of the size
    atlas = atlas.quantize(colors=256, method=Image.FASTOCTREE, dither=Image.Dither.NONE)
    buf = io.BytesIO()
    atlas.save(buf, "PNG", optimize=True)
    data = buf.getvalue()

    native = Path(__file__).resolve().parent.parent / "native"
    with open(native / "button_atlas.h", "w") as o:
        o.write("// generated by tools/make_button_atlas.py: the touch buttons' artwork, packed in one atlas\n#pragma once\n\n")
        o.write("namespace btnatlas {\n\n")
        o.write("// a button's place in the atlas: its corners as shares of the atlas\nstruct Cell {\n    float u0, v0, u1, v1;\n};\n")
        o.write("// a cell is taller than wide by the badge above the circle: its height in widths, and the circle's centre as\n// a share of that height from the top\n")
        o.write(f"constexpr float kAspect = {TH / S:.6f}f;\nconstexpr float kCentreY = {(TH - S / 2) / TH:.6f}f;\n\n")
        o.write("enum Art : int { " + ", ".join("k" + n for n, *_ in cells) + ", kCount };\n\n")
        o.write("constexpr Cell kCells[kCount] = {\n")
        for n, u0, v0, u1, v1 in cells:
            o.write(f"    {{{u0:.6f}f, {v0:.6f}f, {u1:.6f}f, {v1:.6f}f}},  // {n}\n")
        o.write("};\n\n}  // namespace btnatlas\n")
    with open(native / "button_atlas_png.h", "w") as o:
        o.write("// generated by tools/make_button_atlas.py: the atlas as a PNG\n#pragma once\n\nnamespace btnatlas {\n\n")
        o.write("static const unsigned char kPng[] = {\n")
        for i in range(0, len(data), 24):
            o.write("    " + ",".join(f"0x{b:02x}" for b in data[i:i + 24]) + ",\n")
        o.write("};\n\n}  // namespace btnatlas\n")
    print(f"atlas {aw}x{ah}, png {len(data)} bytes")


if __name__ == "__main__":
    main()
