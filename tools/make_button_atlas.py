#!/usr/bin/env python3
"""Packs the touch button artwork into one atlas and writes the two headers the host code includes.

    python3 tools/make_button_atlas.py path/to/button/folder

Reads the button PNGs (see FILES) from that folder and writes
  native/button_atlas.h      the cell table (UVs), read by touch.cpp
  native/button_atlas_png.h  the atlas PNG as a byte array, decoded once by vulkan.cpp
Every button is a circle: each is cropped to the circle and scaled to the same square cell. The stick's thumb is
scaled with the stick's base, so it keeps its size against it. Needs Pillow.
"""
import io
import sys
from pathlib import Path

from PIL import Image

S = 320          # a cell's side
PAD = 4          # transparent border around each cell, against bleeding when sampled
COLS = 5

# enum name, file in the folder
FILES = [
    ("Aim", "Aim.png"),
    ("Back", "Back.png"),
    ("Crouch", "Crouch.png"),
    ("Fire", "Fire.png"),
    ("Mode", "change_mode.png"),
    ("Grenade", "grenade.png"),
    ("Gyro", "Gyroscope.png"),
    ("Health", "medic.png"),
    ("Use", "Action.png"),
    ("Melee", "Melee.png"),
    ("Pause", "pause.png"),
    ("Reload", "Reload.png"),
    ("Suppressor", "Surpressor.png"),
    ("Weapon", "change_weapon.png"),
    ("Up", "dpad up.png"),
    ("Down", "dpad down.png"),
    ("Left", "dpad left.png"),
    ("Right", "dpad right.png"),
    ("StickBase", "analog_base.png"),
    ("Stick", "analog_stick.png"),
]


def circle(path):
    """The picture cropped to its circle (the transparent margin off) and scaled to a cell."""
    im = Image.open(path).convert("RGBA")
    return im.crop(im.getchannel("A").getbbox()), im


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    src = Path(sys.argv[1])
    rows = -(-len(FILES) // COLS)
    cw = S + 2 * PAD
    aw, ah = cw * COLS, cw * rows
    atlas = Image.new("RGBA", (aw, ah), (0, 0, 0, 0))
    base_w = circle(src / "analog_base.png")[0].width
    cells = []
    for i, (name, f) in enumerate(FILES):
        if name == "Stick":  # no crop: its size against the base's is the artwork's
            im = Image.open(src / f).convert("RGBA")
            w = round(im.width * S / base_w)
            h = round(im.height * S / base_w)
            im = im.resize((w, h), Image.LANCZOS)  # Pillow resizes RGBA premultiplied
            cell = Image.new("RGBA", (S, S), (0, 0, 0, 0))
            cell.alpha_composite(im, ((S - w) // 2, (S - h) // 2))
        else:
            cell = circle(src / f)[0].resize((S, S), Image.LANCZOS)
        x, y = (i % COLS) * cw + PAD, (i // COLS) * cw + PAD
        atlas.alpha_composite(cell, (x, y))
        cells.append((name, x / aw, y / ah, (x + S) / aw, (y + S) / ah))
    # flat colours with soft edges: a 256-colour palette with alpha keeps it sharp at a fraction of the size
    atlas = atlas.quantize(colors=256, method=Image.FASTOCTREE, dither=Image.Dither.NONE)
    buf = io.BytesIO()
    atlas.save(buf, "PNG", optimize=True)
    data = buf.getvalue()

    native = Path(__file__).resolve().parent.parent / "native"
    with open(native / "button_atlas.h", "w") as o:
        o.write("// generated by tools/make_button_atlas.py: the touch buttons' artwork, packed in one atlas\n#pragma once\n\n")
        o.write("namespace btnatlas {\n\n")
        o.write("// a button's place in the atlas: its corners as shares of the atlas; every cell is a square, the circle filling it\n")
        o.write("struct Cell {\n    float u0, v0, u1, v1;\n};\n\n")
        o.write("enum Art : int { " + ", ".join("k" + n for n, *_ in cells) + ", kCount };\n\n")
        o.write("constexpr Cell kCells[kCount] = {\n")
        for n, u0, v0, u1, v1 in cells:
            o.write(f"    {{{u0:.6f}f, {v0:.6f}f, {u1:.6f}f, {v1:.6f}f}},  // {n}\n")
        o.write("};\n\n}  // namespace btnatlas\n")
    with open(native / "button_atlas_png.h", "w") as o:
        o.write("// generated by tools/make_button_atlas.py: the atlas as a PNG\n#pragma once\n\nnamespace btnatlas {\n\n")
        o.write("static const unsigned char kPng[] = {\n")
        for i in range(0, len(data), 24):
            o.write("    " + ",".join(f"0x{b:02x}" for b in data[i:i + 24]) + ",\n")
        o.write("};\n\n}  // namespace btnatlas\n")
    print(f"atlas {aw}x{ah}, png {len(data)} bytes")


if __name__ == "__main__":
    main()
